export function getCardDefinition(definitionId: string): CardDefinition | undefined {
  // Check for crafted cards that follow the burning_toaster pattern
  if (definitionId === 'burning_toaster' || definitionId.includes('crafted_toaster_burning_essence') || definitionId.includes('crafted_burning_essence_toaster')) {
    return CARD_DEFINITIONS.burning_toaster;
  }
  return CARD_DEFINITIONS[definitionId];
}

export function findRecipeOutput(inputA: string, inputB: string): string | null {
  for (const recipe of Object.values(SYNTHESIS_RECIPES)) {
    const [a, b] = recipe.inputs;
    if ((inputA === a && inputB === b) || (inputA === b && inputB === a)) {
      return recipe.output;
    }
  }
  return null;
}
